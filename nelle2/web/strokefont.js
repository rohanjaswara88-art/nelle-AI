function glyphWidth(strokes) {
  return Math.max(...strokes.flat().map(([x]) => x));
}

/**
 * Lay a string out as strokes, centred on (0, 0) and scaled so it is at most `maxWidth` wide and
 * `maxHeight` tall (in the caller's units, y up). Unknown characters are skipped.
 * Returns { strokes: [[ [x, y], ... ], ...], letters: [index of the letter for each stroke] }.
 */
export function layoutText(text, { maxWidth = 1.8, maxHeight = 0.7 } = {}) {
  const placed = [];
  const letters = [];
  let cursor = 0;
  let letter = 0;
  for (const char of text.toUpperCase()) {
    if (char === " ") {
      cursor += SPACE;
      continue;
    }
    const glyph = GLYPHS[char];
    if (!glyph) continue;
    for (const stroke of glyph) {
      placed.push(stroke.map(([x, y]) => [x + cursor, y]));
      letters.push(letter);
    }
    cursor += glyphWidth(glyph) + GAP;
    letter += 1;
  }
  if (!placed.length) return { strokes: [], letters: [] };
  const width = cursor - GAP;
  const scale = Math.min(maxWidth / width, maxHeight / GLYPH_HEIGHT);
  const strokes = placed.map((stroke) => stroke.map(([x, y]) => [(x - width / 2) * scale, (y - GLYPH_HEIGHT / 2) * scale]));
  return { strokes, letters };
}
